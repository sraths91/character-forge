// M64 phase 1.5 — docs/M45-CALIBRATOR-RESULTS.md matches its generator.
//
// The doc's tables are the verbatim output of
// `node scripts/calibrator-baseline.mjs` (100 iterations × 33 encounters,
// seed 1), pasted between the `calibrator-baseline` markers. This test
// runs the script and diffs its output against that block, so a change
// that moves the simulator's numbers has to regenerate the doc (and say
// why) in the same commit.
//
// Skipped unless CF_CALIBRATOR_DOC=1: the run costs ~1.5e10 instructions,
// too much for every local `npm test`. CI runs it in its own step.
//
// Regenerate:  node scripts/calibrator-baseline.mjs > /tmp/tables.md
// and paste it between the markers.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const DOC = new URL('../../docs/M45-CALIBRATOR-RESULTS.md', import.meta.url);
const SCRIPT = fileURLToPath(new URL('../../scripts/calibrator-baseline.mjs', import.meta.url));
const BEGIN = '<!-- calibrator-baseline:begin -->';
const END = '<!-- calibrator-baseline:end -->';
const ENABLED = process.env.CF_CALIBRATOR_DOC === '1';

/**
 * The generated block of the doc (between the markers), trimmed.
 * @param {string} doc — the markdown source
 * @returns {string}
 */
function generatedBlock(doc) {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  assert.ok(a >= 0 && b > a, `the doc needs one ${BEGIN} … ${END} block`);
  assert.equal(doc.indexOf(BEGIN, a + 1), -1, 'exactly one begin marker');
  return doc.slice(a + BEGIN.length, b).trim();
}

test('calibrator doc: the generated block has its markers (always runs)', () => {
  const block = generatedBlock(readFileSync(DOC, 'utf8'));
  assert.match(block, /Generated by `node scripts\/calibrator-baseline\.mjs`\./);
  assert.match(block, /^## Summary$/m);
});

test('calibrator doc: the tables equal `node scripts/calibrator-baseline.mjs` output',
  { skip: ENABLED ? false : 'set CF_CALIBRATOR_DOC=1 (CI does)' }, () => {
    const printed = execFileSync(process.execPath, [SCRIPT], { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 22 });
    const want = printed.trim();
    const have = generatedBlock(readFileSync(DOC, 'utf8'));
    if (have !== want) {
      const a = have.split('\n');
      const b = want.split('\n');
      const diff = [];
      for (let i = 0; i < Math.max(a.length, b.length); i++) {
        if (a[i] !== b[i]) diff.push(`line ${i + 1}\n  doc:    ${a[i] ?? '(none)'}\n  script: ${b[i] ?? '(none)'}`);
      }
      assert.fail(`docs/M45-CALIBRATOR-RESULTS.md is stale; regenerate it with scripts/calibrator-baseline.mjs and say why the numbers moved.\n${diff.slice(0, 12).join('\n')}`);
    }
  });
